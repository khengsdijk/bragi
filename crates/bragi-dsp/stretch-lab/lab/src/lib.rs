use std::path::PathBuf;
use wav::Audio;

/// Repository root, computed from this crate's manifest directory.
#[must_use]
pub fn repo_root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../../../../")
        .canonicalize()
        .unwrap()
}

/// `fixtures/audio/<name>` in the repository.
#[must_use]
pub fn fixture(name: &str) -> PathBuf {
    repo_root().join("fixtures/audio").join(name)
}

/// Deterministic 120 BPM two-bar stereo drum loop: kick on every beat-1 and beat-3, snare on
/// every beat-2 and beat-4 (eight prominent hits). Self-made, generated by this function, so it
/// is licence-clean.
///
/// No hi-hats: their short, quiet attacks sit near the objective onset detector's floor and
/// make the "one hit stays one hit" measure noisy. Kick and snare are the hits the listening
/// check actually listens to.
///
/// The two channels share the drum bus and add independent, quiet "room" noise, so the stereo
/// image is exercised without the channels being trivially identical.
#[must_use]
pub fn drum_loop(sr: u32) -> Audio {
    let beat = (sr / 2) as usize; // 120 BPM
    let frames = beat * 8;
    let mut left = vec![0.0f32; frames];
    let mut right = vec![0.0f32; frames];

    let kick = |buf: &mut [f32], at: usize| {
        let n = (0.30 * f64::from(sr)) as usize;
        for i in 0..n {
            if at + i >= buf.len() {
                break;
            }
            let t = i as f64 / f64::from(sr);
            let freq = 48.0 + 110.0 * (-t * 22.0).exp();
            let env = (-t * 9.0).exp();
            let phase = 2.0 * std::f64::consts::PI * freq * t;
            buf[at + i] += (0.9 * env * phase.sin()) as f32;
        }
    };
    let snare = |buf: &mut [f32], at: usize, seed: u64| {
        let n = (0.18 * f64::from(sr)) as usize;
        let mut rng = signals::Rng::new(seed);
        for i in 0..n {
            if at + i >= buf.len() {
                break;
            }
            let t = i as f64 / f64::from(sr);
            let env = (-t * 26.0).exp();
            let body = (2.0 * std::f64::consts::PI * 190.0 * t).sin();
            buf[at + i] += (0.55 * env * (0.6 * body + 0.9 * f64::from(rng.bipolar()))) as f32;
        }
    };

    for bar in 0..2 {
        let base = bar * beat * 4;
        for &slot in &[0usize, 2] {
            kick(&mut left, base + slot * beat);
            kick(&mut right, base + slot * beat);
        }
        for (i, &slot) in [1usize, 3].iter().enumerate() {
            snare(
                &mut left,
                base + slot * beat,
                11 + bar as u64 * 2 + i as u64,
            );
            snare(
                &mut right,
                base + slot * beat,
                71 + bar as u64 * 2 + i as u64,
            );
        }
    }

    // Quiet, decorrelated room noise so the channels are not identical.
    let mut rl = signals::Rng::new(9001);
    let mut rr = signals::Rng::new(9002);
    for i in 0..frames {
        left[i] += 0.004 * rl.bipolar();
        right[i] += 0.004 * rr.bipolar();
    }
    Audio {
        sample_rate: sr,
        channels: vec![left, right],
    }
}
