#!/usr/bin/env node
/**
 * The schema code generator behind `pnpm schemas:gen` (specs/12-roadmap.md WP-0.2).
 *
 * Reads the JSON Schemas under `packages/schemas/{song,analysis,jobs,api}`, bundles them into one
 * 2020-12 document, and generates from that single artifact:
 *
 *   generated/bundle.schema.json                                  every schema, every $ref rewritten
 *   src/generated/types.ts                                        TypeScript types (json-schema-to-typescript)
 *   src/generated/ajv-validators.js                               precompiled Ajv 2020-12 validators
 *   src/generated/validators.ts                                   a typed façade over the above
 *   crates/bragi-model/src/generated/mod.rs                       Rust types (typify)
 *   services/workers/bragi_common/src/bragi_common/generated/models.py   Pydantic v2 models
 *
 * Precompiled validators are not an optimisation: the UI runs under a strict CSP
 * (specs/01-architecture.md §10), so runtime Ajv (which compiles schemas with `new Function`) must
 * not ship to the browser.
 *
 * `--check` regenerates everything into memory or a temp file and fails, listing the stale files,
 * if any output differs from what is committed. Run by `pnpm verify` and by CI.
 *
 * Everything in `**\/generated/**` is written by this script and must never be hand-edited
 * (specs/13-agent-guide.md §1): change the schemas, run `pnpm schemas:gen`, commit both.
 */
import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";
import { compile as compileTypeScript } from "json-schema-to-typescript";

import { BUNDLE_ID, bundleSchemas, readSchemaFiles } from "./bundle.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
/** The repository root. */
const ROOT = join(HERE, "..", "..", "..");
/** The schema root (`packages/schemas`). */
const SCHEMAS = join(HERE, "..");

/** `true` when `--check` was passed: compare with the committed files instead of writing. */
const CHECK = process.argv.includes("--check");

/** Every output this script owns, relative to the repository root. */
const OUTPUTS = {
  bundle: "packages/schemas/generated/bundle.schema.json",
  types: "packages/schemas/src/generated/types.ts",
  ajv: "packages/schemas/src/generated/ajv-validators.js",
  validators: "packages/schemas/src/generated/validators.ts",
  rust: "crates/bragi-model/src/generated/mod.rs",
  python: "services/workers/bragi_common/src/bragi_common/generated/models.py",
};

const BANNER = (what, extra = [], comment = "//") =>
  [
    `${comment} GENERATED by \`pnpm schemas:gen\` — do not edit (specs/13-agent-guide.md §1).`,
    `${comment} ${what}`,
    `${comment} Source of truth: packages/schemas/{song,analysis,jobs,api}/**/*.schema.json`,
    ...extra,
  ].join("\n");

/**
 * Deep-copies a JSON value.
 *
 * @template T
 * @param {T} value
 * @returns {T}
 */
const clone = (value) => JSON.parse(JSON.stringify(value));

/**
 * Removes `description` siblings from every `$ref`.
 *
 * JSON Schema 2020-12 allows them, and the bundle keeps them because the Rust and Python
 * generators document the referenced type; `json-schema-to-typescript` instead treats
 * `{ "$ref": …, "description": … }` as a *new* anonymous type and emits `AssetHash1`,
 * `AssetHash2`, … . Stripping them for that one generator keeps the type names equal to the
 * `$def` names.
 *
 * @param {unknown} node
 * @returns {unknown}
 */
function withoutRefDescriptions(node) {
  if (Array.isArray(node)) {
    for (const item of node) withoutRefDescriptions(item);
    return node;
  }
  if (typeof node === "object" && node !== null) {
    const record = /** @type {Record<string, unknown>} */ (node);
    if (typeof record.$ref === "string") {
      for (const key of Object.keys(record)) if (key !== "$ref") delete record[key];
      return record;
    }
    for (const value of Object.values(record)) withoutRefDescriptions(value);
  }
  return node;
}

/**
 * Emits the TypeScript types.
 *
 * json-schema-to-typescript starts at the schema root, so the bundle's root is a synthetic
 * `oneOf` over every root type; that also proves the bundle's reachability check. The synthetic
 * union itself is dropped from the output.
 *
 * @param {Record<string, unknown>} bundle
 * @param {string[]} rootTypes
 * @returns {Promise<string>}
 */
async function generateTypes(bundle, rootTypes) {
  const defs = withoutRefDescriptions(clone(bundle.$defs));
  const wrapper = {
    $schema: bundle.$schema,
    title: "BragiRootTypes",
    $defs: defs,
    oneOf: rootTypes.map((name) => ({ $ref: `#/$defs/${name}` })),
  };
  const generated = await compileTypeScript(wrapper, "BragiRootTypes", {
    bannerComment: "",
    cwd: SCHEMAS,
    additionalProperties: false,
    declareExternallyReferenced: true,
    unknown: true,
    style: { singleQuote: false, semi: true, bracketSpacing: true },
  });
  const union = /^export type BragiRootTypes =[\s\S]*?;\n/m;
  if (!union.test(generated)) throw new Error("the synthetic BragiRootTypes union was not emitted");
  return `${BANNER("TypeScript types for every Bragi JSON Schema type.")}\n\n${generated
    .replace(union, "")
    .replace(/\n{3,}/g, "\n\n")
    .trimEnd()}\n`;
}

/**
 * Compiles every root type into one standalone Ajv module.
 *
 * Each root type is registered as a schema whose whole body is a `$ref` into the bundle, so Ajv
 * compiles the shared `$defs` exactly once and the emitted module stays one file.
 *
 * @param {Record<string, unknown>} bundle
 * @param {string[]} rootTypes
 * @returns {string}
 */
function generateValidators(bundle, rootTypes) {
  const ajv = new Ajv2020({ strict: true, allErrors: true, code: { source: true, esm: true } });
  ajv.addSchema(bundle);
  /** @type {Record<string, unknown>} */
  const map = {};
  for (const name of rootTypes) {
    const id = `https://bragi.app/schemas/${name}`;
    ajv.addSchema({ $id: id, $ref: `${BUNDLE_ID}#/$defs/${name}` });
    map[name] = id;
  }
  return withValidatorsBanner(toEsm(standaloneCode(ajv, map)));
}

/**
 * Rewrites the CommonJS `require()`s Ajv emits for its runtime helpers into ESM imports.
 *
 * Ajv's standalone output is ESM with respect to its own exports, but it keeps
 * `require("ajv/dist/runtime/…").default` for helpers such as `minLength`'s `ucs2length`. An ES
 * module has no `require`, so a Node or Vite consumer would fail at import time; the web bundle
 * cannot use it either (specs/01-architecture.md §10).
 *
 * The helper module is CommonJS, and its default export is read differently by Node (which binds
 * `module.exports`, so the function is at `.default.default`) and by bundlers such as Vite (which
 * honour `__esModule`, so it is at `.default`). One namespace import plus `??` covers both.
 *
 * @param {string} code
 * @returns {string}
 */
function toEsm(code) {
  /** @type {Map<string, string>} */
  const helpers = new Map();
  for (const call of code.match(/require\("[^"]+"\)\.default/g) ?? []) {
    const specifier = JSON.parse(call.slice("require(".length, -".default".length - 1));
    if (!helpers.has(specifier)) helpers.set(specifier, `__ajvRuntime${helpers.size}`);
  }
  let rewritten = code;
  for (const [specifier, name] of helpers) {
    rewritten = rewritten
      .split(`require(${JSON.stringify(specifier)}).default`)
      .join(`${name}Default`);
  }
  if (rewritten.includes("require(")) {
    throw new Error(
      "the Ajv output references a CommonJS helper in a form this script cannot rewrite",
    );
  }
  const prelude = [...helpers]
    .map(
      ([specifier, name]) =>
        `import * as ${name} from "${specifier}.js";\nconst ${name}Default = ${name}.default.default ?? ${name}.default;`,
    )
    .join("\n");
  return `${prelude}${prelude === "" ? "" : "\n"}${rewritten}`;
}

/**
 * Fails if a `require()` survived, and prepends the generated-file banner.
 *
 * @param {string} code
 * @returns {string}
 */
function withValidatorsBanner(code) {
  if (code.includes("require(")) {
    throw new Error("the Ajv output still needs a CommonJS `require`, so it is not ESM");
  }
  const banner = BANNER("Precompiled Ajv 2020-12 validators, one per root schema type.", [
    "//",
    "// Minified validator code: never typechecked, never read by hand. The typed surface is",
    "// ./validators.ts, which imports this module and gives every validator its ValidateFunction<T>.",
    "// @ts-nocheck",
  ]);
  return `${banner}\n${code}`;
}

/**
 * Emits the typed façade over `ajv-validators.js`, plus the list of root types.
 *
 * The façade is what the rest of the repository imports: it gives every validator a
 * `ValidateFunction<T>` type, so a validator and its type cannot disagree.
 *
 * @param {string[]} rootTypes
 * @returns {string}
 */
function generateValidatorFacade(rootTypes) {
  const lines = [
    BANNER("A typed façade over ./ajv-validators.js; one validator per root schema type."),
    "",
    'import type { ValidateFunction } from "ajv";',
    "",
    'import type * as Types from "./types.js";',
    'import * as validators from "./ajv-validators.js";',
    "",
    "/** Every root schema type in `generated/bundle.schema.json`, sorted. */",
    `export const ROOT_TYPES = [${rootTypes.map((name) => `"${name}"`).join(", ")}] as const;`,
    "",
    "/** A root schema type in `generated/bundle.schema.json`. */",
    "export type RootType = (typeof ROOT_TYPES)[number];",
    "",
  ];
  for (const name of rootTypes) {
    lines.push(
      `/** Validates a \`${name}\` (see \`packages/schemas/song|analysis|jobs|api\`). */`,
      `export const validate${name}: ValidateFunction<Types.${name}> = validators.${name} as ValidateFunction<Types.${name}>;`,
      "",
    );
  }
  return `${lines.join("\n").trimEnd()}\n`;
}

/**
 * Runs `crates/bragi-schemas-codegen` (typify) over the bundle, adds the header and `ROOT_TYPES`,
 * and formats the result with `rustfmt`.
 *
 * `rustfmt` is not optional: typify's `prettyplease` output is readable but not rustfmt-clean, and
 * `pnpm verify` runs `cargo fmt --all -- --check`.
 *
 * @param {string} bundlePath
 * @param {string[]} rootTypes
 * @returns {string}
 */
function generateRust(bundlePath, rootTypes) {
  return withTempDir((dir) => {
    const out = join(dir, "mod.rs");
    run("cargo", ["run", "-q", "-p", "bragi-schemas-codegen", "--", bundlePath, out], ROOT);
    const header = BANNER("Rust types for every Bragi JSON Schema type, generated by typify.", [
      "//",
      "// Generated code is held to the same build as hand-written code except for the lints below:",
      "// typify qualifies every path (`::std::string::String`), documents `$def` types itself and",
      "// `unwrap()`s the regexes it compiles at startup.",
      "#![allow(unused_qualifications, missing_docs, clippy::unwrap_used, clippy::expect_used)]",
      "",
    ]);
    const list = rootTypes.map((name) => `    "${name}",`).join("\n");
    const rootTypeConst = `/// Every root schema type in \`packages/schemas/generated/bundle.schema.json\`, sorted.\n///\n/// Lets a test assert that the Rust types cover the same root types as the TypeScript and\n/// Python generators (specs/12-roadmap.md WP-0.2).\npub const ROOT_TYPES: &[&str] = &[\n${list}\n];\n`;
    writeFileSync(out, `${header}\n${readFileSync(out, "utf8").trimEnd()}\n\n${rootTypeConst}`);
    run("rustfmt", ["--config-path", join(ROOT, "rustfmt.toml"), out], ROOT);
    return readFileSync(out, "utf8");
  });
}

/**
 * Runs `datamodel-code-generator` (Pydantic v2) over the bundle.
 *
 * @param {string} bundlePath
 * @returns {string} the generator's raw output; {@link tidyPython} post-processes it
 */
function generatePython(bundlePath) {
  return withTempDir((dir) => {
    const out = join(dir, "models.py");
    run(
      "uv",
      [
        "run",
        "--directory",
        join(ROOT, "services/workers"),
        "datamodel-codegen",
        "--input",
        bundlePath,
        "--input-file-type",
        "jsonschema",
        "--output",
        out,
        "--output-model-type",
        "pydantic_v2.BaseModel",
        "--target-python-version",
        "3.12",
        "--use-standard-collections",
        "--use-union-operator",
        "--use-type-alias",
        "--use-annotated",
        "--use-title-as-name",
        "--use-schema-description",
        "--disable-timestamp",
        "--formatters",
        "builtin",
      ],
      ROOT,
    );
    return readFileSync(out, "utf8");
  });
}

/**
 * Removes the two artifacts `datamodel-code-generator` leaves behind and appends `ROOT_TYPES`.
 *
 * The bundle's root is intentionally bare (a `$defs` container, like `song/common.schema.json`),
 * which the generator reports as `type Model = Any`; and PEP 695 `type` aliases are what make it
 * possible to use a generated type as a `dict` key (a `RootModel` subclass is unhashable).
 *
 * @param {string} code
 * @param {string[]} rootTypes
 * @returns {string}
 */
function tidyPython(code, rootTypes) {
  const withoutRootModel = code.replace(/^type Model = Any\n\n\n/m, "");
  if (withoutRootModel === code) throw new Error("the generated `type Model = Any` was not found");
  const usesAny = withoutRootModel.replace(/^from typing import[^\n]*\n/m, "").includes("Any");
  const withoutAny = usesAny
    ? withoutRootModel
    : withoutRootModel.replace(/^from typing import ([^\n]*)\n/m, (_match, names) => {
        const kept = names
          .split(",")
          .map((name) => name.trim())
          .filter((name) => name !== "Any");
        return `from typing import ${kept.join(", ")}\n`;
      });
  const list = rootTypes.map((name) => `    "${name}",`).join("\n");
  const header = BANNER(
    "Pydantic v2 models for every Bragi JSON Schema type.",
    ["# Also removes datamodel-codegen's placeholder root model and appends ROOT_TYPES."],
    "#",
  );
  return `${header}\n${withoutAny.trimEnd()}\n\n\n# Every root schema type in generated/bundle.schema.json, sorted.\nROOT_TYPES: tuple[str, ...] = (\n${list}\n)\n`;
}

/**
 * Checks that the error-code registry and the `ErrorCode` enum have not drifted
 * (specs/05-backend-and-jobs.md §2).
 *
 * @param {Record<string, unknown>} bundle
 */
function checkErrorCodes(bundle) {
  const registryPath = join(SCHEMAS, "api/errors.json");
  const registry = JSON.parse(readFileSync(registryPath, "utf8"));
  const codes = registry.codes.map((entry) => entry.code);
  const defs = /** @type {Record<string, { enum?: string[] }>} */ (bundle.$defs);
  const enumCodes = defs.ErrorCode?.enum ?? [];
  const missing = codes.filter((code) => !enumCodes.includes(code));
  const extra = enumCodes.filter((code) => !codes.includes(code));
  if (missing.length > 0 || extra.length > 0) {
    throw new Error(
      `api/errors.json and the ErrorCode enum in api/error.schema.json disagree:\n` +
        `  only in errors.json: ${missing.join(", ") || "(none)"}\n` +
        `  only in the enum:   ${extra.join(", ") || "(none)"}`,
    );
  }
}

/**
 * Runs a command, throwing with its status when it fails.
 *
 * @param {string} command
 * @param {string[]} args
 * @param {string} cwd
 */
function run(command, args, cwd) {
  const result = spawnSync(command, args, { cwd, stdio: ["ignore", "inherit", "inherit"] });
  if (result.error) throw result.error;
  if (result.status !== 0) {
    throw new Error(`${command} ${args.join(" ")} exited with status ${result.status}`);
  }
}

/**
 * Runs `body` with a fresh temporary directory that is removed afterwards.
 *
 * @param {(dir: string) => string} body
 * @returns {string}
 */
function withTempDir(body) {
  const dir = mkdtempSync(join(tmpdir(), "bragi-schemas-"));
  try {
    return body(dir);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

/**
 * Compares generated files with what is committed, or writes them out.
 *
 * @param {Record<string, string>} files
 * @returns {number} the process exit code
 */
function emit(files) {
  /** @type {string[]} */
  const stale = [];
  for (const [path, content] of Object.entries(files)) {
    const absolute = join(ROOT, path);
    const current = existsSync(absolute) ? readFileSync(absolute, "utf8") : undefined;
    if (current === content) continue;
    if (CHECK) {
      stale.push(path);
      continue;
    }
    mkdirSync(dirname(absolute), { recursive: true });
    writeFileSync(absolute, content);
    process.stdout.write(`${current === undefined ? "created" : "updated"} ${path}\n`);
  }
  if (stale.length === 0) return 0;
  process.stderr.write(
    `Generated code is stale. Run \`pnpm schemas:gen\` and commit the result:\n${stale
      .map((path) => `  - ${path}`)
      .join("\n")}\n`,
  );
  return 1;
}

/**
 * The whole pipeline.
 *
 * @returns {Promise<number>}
 */
async function main() {
  const files = readSchemaFiles(SCHEMAS);
  const { bundle, rootTypes } = bundleSchemas(files);
  checkErrorCodes(bundle);

  const bundleText = `${JSON.stringify(bundle, null, 2)}\n`;
  const types = await generateTypes(bundle, rootTypes);
  const ajv = generateValidators(bundle, rootTypes);
  const validators = generateValidatorFacade(rootTypes);

  // The Rust and Python generators read the bundle from disk; they get the freshly built one (not
  // the committed file, which may be stale) so `--check` cannot pass on a stale bundle.
  const { rust, python } = withTempDir((dir) => {
    const bundlePath = join(dir, "bundle.schema.json");
    writeFileSync(bundlePath, bundleText);
    return {
      rust: generateRust(bundlePath, rootTypes),
      python: tidyPython(generatePython(bundlePath), rootTypes),
    };
  });

  const all = {
    [OUTPUTS.bundle]: bundleText,
    [OUTPUTS.types]: types,
    [OUTPUTS.ajv]: ajv,
    [OUTPUTS.validators]: validators,
    [OUTPUTS.rust]: rust,
    [OUTPUTS.python]: python,
  };
  const code = emit(all);
  if (code === 0) {
    process.stdout.write(
      CHECK
        ? `all ${Object.keys(all).length} generated files match the schemas\n`
        : `${Object.keys(all).length} generated files are up to date with the schemas\n`,
    );
  }
  return code;
}

process.exitCode = await main();
