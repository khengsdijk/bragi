#!/usr/bin/env node
/**
 * The schema code generator behind `pnpm schemas:gen` (specs/12-roadmap.md WP-0.2).
 *
 * Reads the JSON Schemas under `packages/schemas/{song,analysis,jobs,api,dsp}`, bundles them into one
 * 2020-12 document, and generates from that single artifact:
 *
 *   generated/bundle.schema.json                                  every schema, every $ref rewritten
 *   src/generated/types.ts                                        TypeScript types (json-schema-to-typescript)
 *   src/generated/ajv-validators.js                               precompiled Ajv 2020-12 validators
 *   src/generated/validators.ts                                   a typed façade over the above
 *   src/generated/fx-catalog.ts                                   `FX_CATALOG`, from crates/bragi-dsp/fx_catalog.json
 *   src/generated/macros.ts                                       `MACROS`, from crates/bragi-dsp/macros.json
 *   crates/bragi-model/src/generated/mod.rs                       Rust types (typify)
 *   services/workers/bragi_common/src/bragi_common/generated/models.py   Pydantic v2 models
 *
 * Precompiled validators are not an optimisation: the UI runs under a strict CSP
 * (specs/01-architecture.md §10), so runtime Ajv (which compiles schemas with `new Function`) must
 * not ship to the browser.
 *
 * `--check` regenerates everything into memory or a temp file and fails, listing the stale files,
 * if any output differs from what is committed. Run by `pnpm verify` and by CI.
 *
 * Everything in `**\/generated/**` is written by this script and must never be hand-edited
 * (specs/13-agent-guide.md §1): change the schemas, run `pnpm schemas:gen`, commit both.
 */
