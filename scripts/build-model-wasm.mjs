#!/usr/bin/env node
/**
 * Builds `packages/model-wasm`: the `wasm-bindgen` package that wraps `crates/bragi-model-wasm`
 * (specs/02-song-model.md §8, specs/01-architecture.md §4).
 *
 * The package is **generated output** and must never be hand-edited (specs/13-agent-guide.md §1):
 * this script is the only thing that writes into it, and it is committed so the UI can import it
 * without a Rust toolchain.
 *
 *   1. `cargo build --target wasm32-unknown-unknown -p bragi-model-wasm --release`
 *   2. `wasm-bindgen --target web --out-dir packages/model-wasm`
 *   3. writes the package.json (`@bragi/model-wasm`)
 *   4. fails if the gzipped `.wasm` exceeds the 1.5 MB budget from specs/12-roadmap.md WP-0.3
 *
 * Prerequisite: `wasm-bindgen` 0.2.129 on PATH (`cargo install wasm-bindgen-cli --version 0.2.129`),
 * the same version pinned in the root `Cargo.toml`.
 */
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { gzipSync } from "node:zlib";

const ROOT = resolve(fileURLToPath(new URL("..", import.meta.url)));
const PACKAGE_DIR = join(ROOT, "packages", "model-wasm");
/** The wasm-bindgen output lives under `generated/`, which Biome already ignores. */
const OUT_DIR = join(PACKAGE_DIR, "generated");
const OUT_NAME = "bragi_model_wasm";
const WASM = join(ROOT, "target", "wasm32-unknown-unknown", "release", "bragi_model_wasm.wasm");
/** The gzipped size budget from specs/12-roadmap.md WP-0.3. */
const BUDGET_BYTES = 1.5 * 1024 * 1024;

/**
 * Runs a command in the repository root.
 *
 * @param {string} command
 * @param {string[]} args
 */
function run(command, args) {
  execFileSync(command, args, { cwd: ROOT, stdio: "inherit" });
}

run("cargo", [
  "build",
  "--target",
  "wasm32-unknown-unknown",
  "-p",
  "bragi-model-wasm",
  "--release",
]);
run("wasm-bindgen", ["--target", "web", "--out-dir", OUT_DIR, "--out-name", OUT_NAME, WASM]);

const packageJson = {
  name: "@bragi/model-wasm",
  version: "0.0.0",
  private: true,
  type: "module",
  description: "wasm-bindgen bindings for bragi-model: the handle-based song-model API (WP-0.3).",
  license: "UNLICENSED",
  // Generated by scripts/build-model-wasm.mjs — do not edit by hand (specs/13-agent-guide.md §1).
  main: `./generated/${OUT_NAME}.js`,
  module: `./generated/${OUT_NAME}.js`,
  types: `./generated/${OUT_NAME}.d.ts`,
  exports: {
    ".": {
      types: `./generated/${OUT_NAME}.d.ts`,
      default: `./generated/${OUT_NAME}.js`,
    },
    "./package.json": "./package.json",
  },
  files: [
    `./generated/${OUT_NAME}.js`,
    `./generated/${OUT_NAME}.d.ts`,
    `./generated/${OUT_NAME}_bg.wasm`,
    `./generated/${OUT_NAME}_bg.wasm.d.ts`,
  ],
  sideEffects: [`./generated/${OUT_NAME}.js`],
};
writeFileSync(join(PACKAGE_DIR, "package.json"), `${JSON.stringify(packageJson, null, 2)}\n`);

const wasm = readFileSync(join(OUT_DIR, `${OUT_NAME}_bg.wasm`));
const gzipped = gzipSync(wasm);
/** @param {number} bytes */
const mib = (bytes) => `${(bytes / 1024 / 1024).toFixed(3)} MiB`;
process.stdout.write(
  `packages/model-wasm: ${mib(wasm.length)} wasm, ${mib(gzipped.length)} gzipped ` +
    `(budget ${mib(BUDGET_BYTES)})\n`,
);
if (gzipped.length > BUDGET_BYTES) {
  process.stderr.write("the gzipped WASM bundle exceeds the 1.5 MB budget (specs/12-roadmap.md)\n");
  process.exitCode = 1;
}
